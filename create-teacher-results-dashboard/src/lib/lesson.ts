/* الخلط العشوائي (Fisher-Yates) — نفس آلية الرابط الأصلي */
export function fisherYates<T>(a: T[]): T[] {
  const arr = a.slice();
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// order[pos] = الفهرس الأصلي للخيار؛ الصحيح أصله 0.
export function makeOrder(n: number, prevPos: number): number[] {
  const o = fisherYates([...Array(n).keys()]);
  const p = o.indexOf(0);
  if (p === prevPos) {
    const k = (p + 1 + Math.floor(Math.random() * (n - 1))) % n;
    [o[p], o[k]] = [o[k], o[p]];
  }
  return o;
}
